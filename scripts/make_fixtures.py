def write(name: str, rows: list[tuple[str, ...]], *, blank_line: bool = False) -> None:
    lines = [T.join(r) for r in rows]
    if blank_line:
        lines.insert(len(lines) // 2, "")
    (OUT / name).write_bytes(("\r\n".join(lines) + "\r\n").encode("cp1252"))


